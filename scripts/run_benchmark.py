"""Generate the T-EVI-010 benchmark report (EVI-010, §26).

Writes ``benchmarks/evidence_segmentation_report.md`` from the locked fixture, running both the
evidence-aware segmenter and the fixed-token baseline over the same document.

    python scripts/run_benchmark.py            # regenerate the report
    python scripts/run_benchmark.py --check    # fail if the committed report is stale

``--check`` is what makes the report an artifact rather than a snapshot somebody took once: a
change to segmentation that moves any number fails it, and the diff shows which metric moved.
The per-case gate itself lives in ``tests/contract/test_evidence_benchmark.py``; this script
publishes, it does not judge.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT))

from lab_brain.evidence.segmentation_benchmark import (  # noqa: E402
    DEFAULT_K,
    evaluate,
    render_report,
)
from lab_brain.ingestion.fixed_token_baseline import (  # noqa: E402
    BASELINE_OVERLAP_TOKENS,
    BASELINE_WINDOW_TOKENS,
    BaselineRun,
    FixedTokenBaselineSegmenter,
)
from lab_brain.ingestion.segmentation import (  # noqa: E402
    DEFAULT_TOKEN_LIMIT,
    SEGMENTER_VERSION,
    token_count,
)
from tests.benchmark_probes import PROBES  # noqa: E402
from tests.evidence_fixtures import (  # noqa: E402
    FIXTURE_NAME,
    fixture_digest,
    parse_fixture,
    segment_fixture,
)

PROJECT = "prj:benchmark"
REPORT_PATH = ROOT / "benchmarks" / "evidence_segmentation_report.md"

_PREAMBLE = f"""# T-EVI-010 — Evidence-Aware Segmentation Benchmark

<!-- Generated by scripts/run_benchmark.py. Do not edit by hand. -->

| | |
|---|---|
| Requirement | `EVI-010` (§6.22, §17.25, `v3.3-a17`) |
| Fixture | `fixtures/evidence/{FIXTURE_NAME}` |
| Fixture digest | `{{digest}}` |
| Document size | {{tokens}} whitespace tokens |
| Evidence-aware token limit | {DEFAULT_TOKEN_LIMIT} (segmenter {SEGMENTER_VERSION}) |
| Fixed-token baseline | window {BASELINE_WINDOW_TOKENS}, overlap {BASELINE_OVERLAP_TOKENS} |
| Retrieval depth | k = {DEFAULT_K}, deterministic BM25 |

**The pass condition is per case, not a score.** §26 fixes the expected outcome for each of the
five fixture cases; the metrics below are published because §26 requires them and because what
they do *not* separate is itself the finding. See `tests/contract/test_evidence_benchmark.py`
for the gate.

## Results
"""

_ANALYSIS = """

## How to read this

The **structural columns** — table context, figure context, locator recovery — are where the two
strategies separate, and each corresponds to a scientific failure: a table value without its
header and unit is a number, a figure without its explanatory prose is a caption, and a unit
without a resolving locator cannot be re-checked by a human.

The **retrieval columns** do not separate them, and on this fixture they favour the baseline.
That is not a defect in the fixture. A {window}-token window over a {tokens}-token document
produces very few, very large units, and large units:

  * score 1.00 on boundary completeness by never really cutting — which is the *opposite* of
    §6.22's Minimum Evidence Boundary, defined as the **smallest** complete unit;
  * flatter precision@k, because retrieving k candidates returns most of the corpus.

So a corpus-level threshold over recall and precision would have selected the strategy §6.22
prohibits. That is the concrete form of the argument `SPEC-ISSUE-013` escalated, and it is why
the maintainer's ruling fixed the outcome per case instead.

## Regression

This file is regenerated by `python scripts/run_benchmark.py` and checked by
`python scripts/run_benchmark.py --check`. Both the fixture and the baseline settings are locked,
so any movement in the table above is a real change in segmentation behaviour rather than noise.
"""


def build_report() -> str:
    document = parse_fixture()
    tokens = sum(token_count(block.text) for block in document.blocks)

    aware = evaluate(
        "evidence-aware",
        segment_fixture(project_id=PROJECT).units,
        PROBES,
        document,
        project_id=PROJECT,
    )
    baseline = evaluate(
        "fixed-token",
        FixedTokenBaselineSegmenter().segment(
            document,
            project_id=PROJECT,
            run=BaselineRun(reason="T-EVI-010 published comparison"),
        ),
        PROBES,
        document,
        project_id=PROJECT,
    )

    preamble = _PREAMBLE.format(digest=fixture_digest(), tokens=tokens)
    analysis = _ANALYSIS.format(window=BASELINE_WINDOW_TOKENS, tokens=tokens)
    return preamble + "\n" + render_report((aware, baseline), PROBES) + analysis


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the report is stale")
    args = parser.parse_args(argv)

    report = build_report()
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)

    if args.check:
        if not REPORT_PATH.is_file():
            print(f"error: {REPORT_PATH.relative_to(ROOT)} does not exist")
            return 1
        current = REPORT_PATH.read_text(encoding="utf-8").replace("\r\n", "\n")
        if current != report:
            print(
                f"error: {REPORT_PATH.relative_to(ROOT)} is stale; run "
                "`python scripts/run_benchmark.py`"
            )
            return 1
        print(f"{REPORT_PATH.relative_to(ROOT)} is current")
        return 0

    REPORT_PATH.write_text(report, encoding="utf-8", newline="\n")
    print(f"wrote {REPORT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
