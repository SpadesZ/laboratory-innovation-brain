"""The versioned message catalog (UX-006, §17.24).

WHAT THE RULE ACTUALLY FORBIDS.

    User-facing text MUST come from a versioned MessageCatalog keyed by reason_code.
    It MUST NOT be generated by an LLM at render time. An LLM-written failure explanation is an
    ungrounded inference presented as system fact, which contradicts P3 / EVI-003.

The second sentence is the reason and it is not a UI concern. A model asked "explain this error to
the user" produces a fluent, plausible account of a system it cannot observe -- and the user reads
it as what the system did. That is an INFERRED claim rendered as OBSERVED, which is the exact
failure EVI-003 exists to prevent, arriving through the one door nobody guards.

So rendering is a lookup. There is no model call anywhere in this module, and
`test_no_render_path_can_reach_a_model_slot` asserts that structurally rather than by convention.

WHY UNKNOWN CODES FAIL CLOSED TO A GENERIC ENTRY. §26's T-UX-006 row requires it: "an unknown
reason_code fails closed to a generic catalog entry". The alternative -- raising -- would turn a
missing catalog row into a second failure on top of the one being reported, and the user would
see a stack trace instead of the original problem. Returning the code itself as prose would leak
an internal identifier into a user surface. A generic entry says "something went wrong, here is
the reference" and keeps the error_id, which is the one thing support needs.

REUSING CODES RATHER THAN INVENTING SYNONYMS. The admission gate already emits seventeen
machine-readable `RefusalReason` values and the ingestion pipeline emits stage reason codes.
Those ARE reason codes; a parallel vocabulary would mean two names for one condition and two
catalog rows that drift. `catalog_for_refusal` maps the existing enum in, and a test asserts
every member resolves.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class Severity(StrEnum):
    """§17.24's `severity`.

    ``WARNING`` exists because §17.23 is explicit that EXTRACTION_WARNING "MUST NOT be rendered
    with failure styling. It is the UNKNOWN discipline working correctly (EVI-002). Rendering it
    as an error trains users to click ACCEPT to clear it, which silently reintroduces
    hallucinated completion."
    """

    INFO = "INFO"
    WARNING = "WARNING"
    ERROR = "ERROR"
    BLOCKED = "BLOCKED"


@dataclass(frozen=True)
class CatalogEntry:
    """§17.24's entry shape, exactly."""

    reason_code: str
    user_summary: str
    user_cause: str
    user_next_steps: tuple[str, ...]
    severity: Severity


#: The code returned when a lookup misses. Named rather than inlined so the fail-closed path is
#: greppable and a test can assert on it without repeating a string.
GENERIC_REASON_CODE = "UNCLASSIFIED_FAILURE"


class MessageCatalog:
    """A versioned, locale-scoped catalog. Lookups only -- no generation, ever.

    Immutable after construction: a catalog that could be edited at runtime is not versioned in
    any useful sense, because two processes could render the same `reason_code` differently while
    both reporting the same `version`.
    """

    def __init__(
        self,
        catalog_id: str,
        locale: str,
        version: str,
        entries: tuple[CatalogEntry, ...],
    ) -> None:
        self.catalog_id = catalog_id
        self.locale = locale
        self.version = version
        self._entries: dict[str, CatalogEntry] = {}
        for entry in entries:
            if entry.reason_code in self._entries:
                raise ValueError(
                    f"catalog {catalog_id}@{version} declares {entry.reason_code} twice; two rows "
                    "for one code means the rendered text depends on iteration order"
                )
            self._entries[entry.reason_code] = entry
        if GENERIC_REASON_CODE not in self._entries:
            raise ValueError(
                f"catalog {catalog_id}@{version} has no {GENERIC_REASON_CODE} entry. UX-006 "
                "requires an unknown code to fail closed to a generic entry, and a catalog "
                "without one has nothing to fail closed *to*"
            )

    @property
    def codes(self) -> frozenset[str]:
        return frozenset(self._entries)

    def resolve(self, reason_code: str) -> CatalogEntry:
        """The entry for ``reason_code``, or the generic one.

        Never raises and never invents. An unknown code is an operational gap -- somebody emitted
        a code nobody wrote a row for -- and the user should still learn that something failed and
        get a reference they can quote.
        """
        entry = self._entries.get(reason_code)
        if entry is not None:
            return entry
        return self._entries[GENERIC_REASON_CODE]

    def knows(self, reason_code: str) -> bool:
        """Whether the code has a real row. Used by the conformance test, not by rendering."""
        return reason_code in self._entries


def _entry(
    code: str,
    summary: str,
    cause: str,
    steps: tuple[str, ...],
    severity: Severity = Severity.ERROR,
) -> CatalogEntry:
    return CatalogEntry(
        reason_code=code,
        user_summary=summary,
        user_cause=cause,
        user_next_steps=steps,
        severity=severity,
    )


