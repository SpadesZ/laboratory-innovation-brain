def default_catalog(locale: str = "en") -> MessageCatalog:
    """The shipped catalog. One version, incremented when entries change."""
    return MessageCatalog(
        catalog_id="lab_brain.messages",
        locale=locale,
        version="1.0.0",
        entries=DEFAULT_ENTRIES,
    )


@dataclass(frozen=True)
class RenderedMessage:
    """What a user surface shows. No technical detail, by construction.

    `technical_detail_ref` is a POINTER and is carried here deliberately: §17.24 requires the
    default payload not to inline technical detail, and a payload with no reference at all would
    leave a user unable to ask for it. Expanding it is `disclosure.py`'s decision.
    """

    reason_code: str
    summary: str
    cause: str
    next_steps: tuple[str, ...]
    severity: Severity
    catalog_version: str
    error_id: str | None = None
    technical_detail_ref: str | None = None
    #: True when the code had no row and the generic entry was substituted.
    fell_back: bool = False


def render(
    catalog: MessageCatalog,
    reason_code: str,
    *,
    error_id: str | None = None,
    technical_detail_ref: str | None = None,
) -> RenderedMessage:
    """Turn a reason code into user-facing text. A lookup, and only a lookup."""
    entry = catalog.resolve(reason_code)
    return RenderedMessage(
        reason_code=entry.reason_code,
        summary=entry.user_summary,
        cause=entry.user_cause,
        next_steps=entry.user_next_steps,
        severity=entry.severity,
        catalog_version=catalog.version,
        error_id=error_id,
        technical_detail_ref=technical_detail_ref,
        fell_back=not catalog.knows(reason_code),
    )


