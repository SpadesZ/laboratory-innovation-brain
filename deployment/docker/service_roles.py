"""Create the services' database roles before `lab-brain admin db-roles` grants them (`init`).

WHO CONNECTS AS WHAT. The migrator -- the database's initial superuser, `lab_brain` -- owns the
schema and runs the migrations, this script, `db-roles` and the operator's bootstrap (`init`), and
nothing else. `web` and `local-models` connect as `lab_brain_app`: a login role that is not a
superuser, owns nothing and, once `db-roles` has run, holds row privileges only, so every trigger
and constraint binds it (`lab_brain.interfaces.deployment.grant_database_roles`). `lab_brain_reader`
is the auditors' role; it reads, and has no login until the operator gives it one.

THE PASSWORD. `lab_brain_app`'s is the one the `secrets` service generated at first start into the
services' own volume, which the migrator's password is not in. It is sent as a SCRAM-SHA-256
verifier, so the password itself never appears in a statement the server could log.

Idempotent: a role that exists is set to exactly these attributes; its password is set only when
the stored verifier does not already match the file.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import os
import sys
from pathlib import Path
from typing import Any

APP_ROLE = "lab_brain_app"
READER_ROLE = "lab_brain_reader"

#: What neither role may do: each of these could step past, or undo, what `db-roles` grants.
_ATTRIBUTES = "NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS"

#: PostgreSQL's default `scram_iterations`.
_ITERATIONS = 4096


def _b64(raw: bytes) -> str:
    return base64.b64encode(raw).decode("ascii")


def scram_verifier(
    password: str, *, salt: bytes | None = None, iterations: int = _ITERATIONS
) -> str:
    """The SCRAM-SHA-256 verifier PostgreSQL stores for `password` (RFC 5802, RFC 7677).

    The password is ASCII (hex, `make_secret.py`), which SASLprep leaves unchanged.
    """
    salt = os.urandom(16) if salt is None else salt
    salted = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, iterations)
    client_key = hmac.new(salted, b"Client Key", hashlib.sha256).digest()
    stored_key = hashlib.sha256(client_key).digest()
    server_key = hmac.new(salted, b"Server Key", hashlib.sha256).digest()
    return f"SCRAM-SHA-256${iterations}:{_b64(salt)}${_b64(stored_key)}:{_b64(server_key)}"


def verifies(stored: str | None, password: str) -> bool:
    """Whether a stored SCRAM-SHA-256 verifier is the one for `password`."""
    if not stored or not stored.startswith("SCRAM-SHA-256$"):
        return False
    try:
        params, _keys = stored.removeprefix("SCRAM-SHA-256$").split("$", 1)
        iterations, salt = params.split(":", 1)
        expected = scram_verifier(
            password, salt=base64.b64decode(salt, validate=True), iterations=int(iterations)
        )
    except ValueError:
        return False
    return hmac.compare_digest(expected, stored)


def ensure_roles(
    c: Any, app_password: str, *, app_role: str = APP_ROLE, reader_role: str = READER_ROLE
) -> list[str]:
    """`app_role` (login, `app_password`) and `reader_role` (no login), as declared."""
    from psycopg import sql

    if len(app_password) < 32:
        raise ValueError("the services' role password is generated by make_secret.py, not shorter")
    lines: list[str] = []
    for role, login in ((app_role, True), (reader_role, False)):
        row = c.execute("SELECT rolpassword FROM pg_authid WHERE rolname = %s", (role,)).fetchone()
        verb = "CREATE ROLE" if row is None else "ALTER ROLE"
        statement = sql.SQL("{} {} {} {}").format(
            sql.SQL(verb),
            sql.Identifier(role),
            sql.SQL(_ATTRIBUTES),
            sql.SQL("LOGIN" if login else "NOLOGIN"),
        )
        password_set = login and (row is None or not verifies(row[0], app_password))
        if password_set:
            statement = sql.SQL("{} PASSWORD {}").format(
                statement, sql.Literal(scram_verifier(app_password))
            )
        c.execute(statement)
        state = "created" if row is None else ("updated" if password_set else "unchanged")
        lines.append(
            f"database role {role}: {state} ({'login' if login else 'no login'}; "
            "not a superuser, cannot create roles or databases, replicate or bypass row security)"
        )
    return lines


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print("usage: service_roles.py APP_PASSWORD_FILE", file=sys.stderr)
        return 2
    url = os.environ.get("LAB_BRAIN_DATABASE_URL")
    if not url:
        print("lab-brain: LAB_BRAIN_DATABASE_URL is not set (the migrator's)", file=sys.stderr)
        return 2
    password = Path(argv[0]).read_text(encoding="ascii").strip()
    import psycopg

    with psycopg.connect(url, autocommit=True) as c:
        for line in ensure_roles(c, password):
            print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
